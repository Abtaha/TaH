def ratio(value,noise):
    return value/noise if noise else (0.0 if not value else math.inf)


def ratios(report):
    s,n,d=report['summary'],report['noise_limits'],report['decision_limits']
    flips=[]
    for measured,reference in zip(s['per_depth'],d['per_depth']):
        count=measured['decision_compared']-measured['visited_mismatches']
        rate=measured['common_decision_mismatches']/count if count else 0
        noise=reference['reference_flips']/reference['reference_common_visited'] if reference['reference_common_visited'] else 0
        flips.append(ratio(rate,noise))
    return [max(flips),ratio(s['pass_count_mismatches']/s['top1_compared'],n['pass_count_mismatches']/n['top1_compared']),ratio(s['logit_rmse'],n['logit_rmse']),ratio(s['top1_mismatches']/s['top1_compared'],n['top1_mismatches']/n['top1_compared'])]


def ratio_cells(reports):
    maxima=[max(values) for values in zip(*(ratios(r) for r in reports))]
    cells=[fmt(value,2) for value in maxima]
    # Exact means both event counts are zero, not merely a zero numerator.
    if all(r['summary']['common_decision_mismatches']==0 and all(d['reference_flips']==0 for d in r['decision_limits']['per_depth']) for r in reports):
        cells[0]='exact'
    if all(r['summary']['pass_count_mismatches']==r['noise_limits']['pass_count_mismatches']==0 for r in reports):
        cells[1]='exact'
    return cells


