def raw(path):
    p = DATA / path
    b = p.read_bytes()
    return lzma.decompress(b) if p.suffix == '.xz' else b


def read(path):
    return json.loads(raw(path))


def fmt(x, digits=3):
    text = f'{x:.{digits}f}'
    return text[1:] if text.startswith('-') and float(text) == 0 else text


def esc(s):
    return ''.join({'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%',
                    '_': r'\_', '#': r'\#', '$': r'\$', '{': r'\{',
                    '}': r'\}', '≥': r'$\geq$', '±': r'$\pm$',
                    '×': r'$\times$', 'Δ': r'$\Delta$', '−': '-'}.get(c, c) for c in str(s))


def table(name, headers, rows, shown=None):
    """LaTeX gets every row; the Markdown README only `shown` (indices) when given."""
    rows = [[str(c) for c in row] for row in rows]
    tex = ['% Generated by analyze.py; requires booktabs.',
           r'\begin{tabular}{' + 'l' * len(headers) + '}', r'\toprule',
           ' & '.join(map(esc, headers)) + r' \\', r'\midrule']
    tex += [' & '.join(map(esc, row)) + r' \\' for row in rows]
    tex += [r'\bottomrule', r'\end{tabular}', '']
    (TABLES / (name + '.tex')).write_text('\n'.join(tex))
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                       '| ' + ' | '.join(['---'] * len(headers)) + ' |'] +
                      ['| ' + ' | '.join(row) + ' |' for i, row in enumerate(rows) if shown is None or i in shown])


def verify():
    manifest = read('MANIFEST.json')
    actual = {str(p.relative_to(DATA)) for p in DATA.rglob('*') if p.is_file()}
    declared = set(manifest['files']) | {'MANIFEST.json'}
    # Optional future R1 evidence must also enter the manifest before analysis.
    if actual != declared:
        raise ValueError(f'Unmanifested/missing files: {actual ^ declared}')
    for name, item in manifest['files'].items():
        b = (DATA / name).read_bytes()
        assert hashlib.sha256(b).hexdigest() == item['sha256'], name
        sources = item.get('sources')
        if sources:
            assert all(s.get('source_path') and len(s.get('source_sha256', '')) == 64 for s in sources), name
        else:
            assert item.get('source_path') and len(item.get('source_sha256', '')) == 64, name
        if item.get('encoding', '').startswith(('xz', 'original')):
            assert hashlib.sha256(raw(name)).hexdigest() == item['source_sha256'], name
    return manifest


def gate(report):
    """Recompute every saved binding metric; never use candidate-derived limits."""
    s, n, d = report['summary'], report['noise_limits'], report['decision_limits']
    checks = []
    for metric in ('logit_mae', 'logit_rmse', 'logit_max_abs'):
        checks.append(s[metric] <= n['g_tf_' + metric + '_limit'])
    checks.append(s['top1_mismatches'] / s['top1_compared'] <= n['g_tf_top1_disagreement_limit'])
    checks.append(s['pass_count_mismatches'] / s['top1_compared'] <= d['pass_count_mismatch_rate_limit'])
    for measured, limit in zip(s['per_depth'], d['per_depth']):
        assert measured['depth'] == limit['depth']
        common = measured['decision_compared'] - measured['visited_mismatches']
        rate = measured['common_decision_mismatches'] / common if common else 0
        checks += [rate <= limit['flip_rate_limit'], measured['max_flip_margin'] <= d['flip_margin_limit']]
    for retained in ('retained_topk_error', 'retained_dense_error'):
        for metric in ('logit_mae', 'logit_rmse', 'logit_max_abs'):
            checks.append(s[retained][metric] <= n[retained]['g_tf_' + metric + '_limit'])
    return 'PASS' if all(checks) else 'FAIL'


def paired(reference, candidates):
    keys = set(reference)
    assert all(set(c) == keys for c in candidates), 'Paired problem coverage differs'
    differences = [st.mean(c[k] for c in candidates)-reference[k] for k in sorted(keys)]
    mean = st.mean(differences)
    se = st.stdev(differences)/math.sqrt(len(differences))
    z = mean/se if se else 0 if mean == 0 else math.copysign(math.inf, mean)
    return len(keys), mean, se, z


def pdf_bars(path, labels, values):
    """Small deterministic vector PDF; no fonts/dependencies/timestamps to vary.

    The same values feed the throughput table; this is a simple bar chart,
    not a statistical figure with independently specified numbers.
    """
    def txt(x,y,text,size=10):
        text=text.replace('\\','\\\\').replace('(','\\(').replace(')','\\)')
        return f'BT /F1 {size} Tf {x} {y} Td ({text}) Tj ET\n'
    stream=txt(30,310,'Generation throughput (tokens/s)',14)
    maximum=max(values)
    for i,(label,value) in enumerate(zip(labels,values)):
        y=270-i*39
        stream+=txt(25,y+5,label)
        stream+=f'0.15 0.38 0.58 rg 180 {y} {270*value/maximum:.5f} 19 re f 0 0 0 rg\n'
        stream+=txt(460,y+5,fmt(value,1))
    stream+=txt(25,20,'Load, capture and warmup excluded; historical runs on the same device.',9)
    content=stream.encode('ascii')
    objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 550 340] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
        b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        f'<< /Length {len(content)} >>\nstream\n'.encode()+content+b'endstream']
    out=bytearray(b'%PDF-1.4\n');offsets=[0]
    for i,obj in enumerate(objects,1):
        offsets.append(len(out));out+=f'{i} 0 obj\n'.encode()+obj+b'\nendobj\n'
    start=len(out);out+=f'xref\n0 {len(objects)+1}\n0000000000 65535 f \n'.encode()
