def raw(path):
    p = DATA / path
    b = p.read_bytes()
    return lzma.decompress(b) if p.suffix == '.xz' else b


def read(path):
    return json.loads(raw(path))


def fmt(x, digits=3):
    text = f'{x:.{digits}f}'
    return text[1:] if text.startswith('-') and float(text) == 0 else text


def esc(s):
    return ''.join({'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%',
                    '_': r'\_', '#': r'\#', '$': r'\$', '{': r'\{',
                    '}': r'\}', '≥': r'$\geq$', '±': r'$\pm$',
                    '×': r'$\times$', 'Δ': r'$\Delta$', '−': '-'}.get(c, c) for c in str(s))


def table(name, headers, rows):
    rows = [[str(c) for c in row] for row in rows]
    tex = ['% Generated by analyze.py; requires booktabs.',
           r'\begin{tabular}{' + 'l' * len(headers) + '}', r'\toprule',
           ' & '.join(map(esc, headers)) + r' \\', r'\midrule']
    tex += [' & '.join(map(esc, row)) + r' \\' for row in rows]
    tex += [r'\bottomrule', r'\end{tabular}', '']
    (TABLES / (name + '.tex')).write_text('\n'.join(tex))
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                       '| ' + ' | '.join(['---'] * len(headers)) + ' |'] +
                      ['| ' + ' | '.join(row) + ' |' for row in rows])


def verify():
    manifest = read('MANIFEST.json')
    actual = {str(p.relative_to(DATA)) for p in DATA.rglob('*') if p.is_file()}
    declared = set(manifest['files']) | {'MANIFEST.json'}
    # Optional future R1 evidence must also enter the manifest before analysis.
    if actual != declared:
        raise ValueError(f'Unmanifested/missing files: {actual ^ declared}')
    for name, item in manifest['files'].items():
        b = (DATA / name).read_bytes()
        assert hashlib.sha256(b).hexdigest() == item['sha256'], name
        if item['encoding'].startswith(('xz', 'original')):
            assert hashlib.sha256(raw(name)).hexdigest() == item['source_sha256'], name
    return manifest


def gate(report):
    """Recompute every saved binding metric; never use candidate-derived limits."""
    s, n, d = report['summary'], report['noise_limits'], report['decision_limits']
    checks = []
    for metric in ('logit_mae', 'logit_rmse', 'logit_max_abs'):
        checks.append(s[metric] <= n['g_tf_' + metric + '_limit'])
    checks.append(s['top1_mismatches'] / s['top1_compared'] <= n['g_tf_top1_disagreement_limit'])
    checks.append(s['pass_count_mismatches'] / s['top1_compared'] <= d['pass_count_mismatch_rate_limit'])
    for measured, limit in zip(s['per_depth'], d['per_depth']):
        assert measured['depth'] == limit['depth']
        common = measured['decision_compared'] - measured['visited_mismatches']
        rate = measured['common_decision_mismatches'] / common if common else 0
        checks += [rate <= limit['flip_rate_limit'], measured['max_flip_margin'] <= d['flip_margin_limit']]
    for retained in ('retained_topk_error', 'retained_dense_error'):
        for metric in ('logit_mae', 'logit_rmse', 'logit_max_abs'):
            checks.append(s[retained][metric] <= n[retained]['g_tf_' + metric + '_limit'])
    return 'PASS' if all(checks) else 'FAIL'


def paired(reference, candidates):
    keys = set(reference)
    assert all(set(c) == keys for c in candidates), 'Paired problem coverage differs'
    differences = [st.mean(c[k] for c in candidates)-reference[k] for k in sorted(keys)]
    mean = st.mean(differences)
    se = st.stdev(differences)/math.sqrt(len(differences))
    z = mean/se if se else 0 if mean == 0 else math.copysign(math.inf, mean)
    return len(keys), mean, se, z


def pdf_bars(path, labels, values):
    """Small deterministic vector PDF; no fonts/dependencies/timestamps to vary.

    The same values feed the throughput table; this is a simple bar chart,
    not a statistical figure with independently specified numbers.
    """
    def txt(x,y,text,size=10):
        text=text.replace('\\','\\\\').replace('(','\\(').replace(')','\\)')
        return f'BT /F1 {size} Tf {x} {y} Td ({text}) Tj ET\n'
    stream=txt(30,310,'Generation throughput (tokens/s)',14)
    maximum=max(values)
    for i,(label,value) in enumerate(zip(labels,values)):
        y=270-i*39
        stream+=txt(25,y+5,label)
        stream+=f'0.15 0.38 0.58 rg 180 {y} {270*value/maximum:.5f} 19 re f 0 0 0 rg\n'
        stream+=txt(460,y+5,fmt(value,1))
    stream+=txt(25,20,'Load, capture and warmup excluded; historical runs on the same device.',9)
    content=stream.encode('ascii')
    objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 550 340] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
        b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        f'<< /Length {len(content)} >>\nstream\n'.encode()+content+b'endstream']
    out=bytearray(b'%PDF-1.4\n');offsets=[0]
    for i,obj in enumerate(objects,1):
        offsets.append(len(out));out+=f'{i} 0 obj\n'.encode()+obj+b'\nendobj\n'
    start=len(out);out+=f'xref\n0 {len(objects)+1}\n0000000000 65535 f \n'.encode()
    for offset in offsets[1:]:out+=f'{offset:010d} 00000 n \n'.encode()
    out+=f'trailer\n<< /Size {len(objects)+1} /Root 1 0 R >>\nstartxref\n{start}\n%%EOF\n'.encode()
    path.write_bytes(out)


def r1_section(policy):
    """Read archived R1 runs through the repository's compare_runs API.

    Import is lazy: the historical chapter needs only the standard library.
    No dataset loader/protocol resolver is called; canonical keys come from
    archived reference CSVs, with cardinality/repeats checked independently.
    """
    def skip(message):
        (TABLES/'r1-analysis.json').unlink(missing_ok=True)
        table('r1', ['Analysis', 'Status'], [['Confirmatory R1', 'Pending: ' + message]])
        return 'Pending: ' + message + '.'
    if not (DATA/'r1/inputs.json').exists():
        return skip('Registered runs not archived')
    index=read('r1/inputs.json')
    if not index.get('complete'):
        return skip('Archived confirmatory inputs are incomplete')
    assert index['reference']['seed']==policy['reference_seed']
    assert sorted(x['seed'] for x in index['engine'])==sorted(policy['engine_seeds'])
    assert len(index['frozen_engine_sha256'])==64
    if any(x['frozen_engine_sha256']!=index['frozen_engine_sha256'] for x in index['engine']):
        raise ValueError('R1 engine revisions differ')
    def confined(path):
        p=(DATA/path).resolve()
        if not p.is_relative_to(DATA.resolve()):
            raise ValueError('R1 paths must remain inside data/')
        return p
    paths=[confined(index['reference']['path']),*[confined(x['path']) for x in index['engine']]]
    if any(not p.exists() or not list(p.rglob('detailed_results.csv')) for p in paths):
        return skip('Some registered R1 run files are missing')
    for spec,p in zip([index['reference'],*index['engine']],paths):
        statuses=list(p.rglob('run_status.json'))
        if not statuses or any(json.loads(f.read_text()).get('status')!='complete' for f in statuses):
            return skip('R1 run completion status is missing or incomplete')
        for f in statuses:
            status=json.loads(f.read_text())
            if status.get('random_seed') != spec['seed']:
                raise ValueError('R1 seed declaration differs from run status: '+str(f))
    import importlib.util
    import sys
    tool=ROOT.parents[1]/'script/tah/evaluation/compare_runs.py'
    if not tool.exists():
        return skip('TODO: compare_runs.py is unavailable; keep inputs pending until the repository analysis tool is restored')
    sys.path.insert(0,str(tool.parent))
    try:
        spec=importlib.util.spec_from_file_location('engine_report_compare',tool)
        module=importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        sys.path.pop(0)
    expected={}
    for ds,n in policy['problems'].items():
        rows=csv.DictReader(io.StringIO(raw(f'evaluations/reference-exploratory/{ds}/detailed_results.csv').decode()))
        expected[ds]={}
        for row in rows:
            expected[ds].setdefault(row['problem_id'],set()).add(int(row['sample_idx']))
        assert len(expected[ds])==n
        assert all(v==set(range(policy['repeats'])) for v in expected[ds].values())
    margin=policy['equivalence_margin_pp']/100
    reference=module._run_group(paths[:1],expected)
    engine=module._run_group(paths[1:],expected)
    earlier=module._run_group([DATA/'evaluations/reference-exploratory'],expected)
    results=[module._pair_analysis(reference,engine,'Confirmatory reference','Engine',expected,margin),
             module._pair_analysis(reference,earlier,'Confirmatory reference','Exploratory reference',expected,margin)]
    output=dict(analysis='R1',comparisons=results,tool_sha256=hashlib.sha256(tool.read_bytes()).hexdigest(),
                frozen_engine_sha256=index['frozen_engine_sha256'],deviations=index.get('deviations',[]))
    (TABLES/'r1-analysis.json').write_text(json.dumps(output,indent=2,sort_keys=True)+'\n')
    rows=[]
    for result in results:
        for ds,r in [('pooled',result['pooled']),*result['datasets'].items()]:
            ratio=r['passes_per_token_ratio']
            pass_ok=ratio is not None and abs(ratio-1)<=read('method.json')['pass_relative_margin']
            rows.append([result['candidate_group'],ds,r['n_problems'],fmt(100*r['mean_difference']),
                         f"[{fmt(100*r['ci90'][0])}, {fmt(100*r['ci90'][1])}]",
                         r['tost_verdict'],fmt(ratio,6) if ratio is not None else 'missing',
                         'PASS' if pass_ok else 'FAIL'])
    return table('r1',['Candidate vs confirmatory reference','Dataset','Problems','Accuracy difference (pp)','Student-t CI (pp)','TOST verdict','Mean passes: candidate/reference','Pass-count check'],rows)+"\n\nDeclared deviations: "+json.dumps(index.get('deviations',[]))


def sample_groups(run,policy):
    groups={}
    for dataset,count in policy['problems'].items():
        rows=list(csv.DictReader(io.StringIO(raw(f'evaluations/{run}/{dataset}/detailed_results.csv').decode())))
        found={}
        for row in rows:
            key=(dataset,row['problem_id']);sample=int(row['sample_idx'])
            group=found.setdefault(key,{})
            if sample in group:raise ValueError('Duplicate exploratory sample')
            group[sample]=row['is_correct'].lower()=='true'
        assert len(found)==count
        for group in found.values():
            assert set(group)==set(range(policy['repeats']))
        groups.update(found)
    return groups


def problem_scores(run,policy):
    return {key:st.mean(group.values()) for key,group in sample_groups(run,policy).items()}


RUNS=[('reference-exploratory','Reference, seed 42'),('engine-seed42','Engine, seed 42'),
      ('engine-seed1234','Engine, seed 1234'),('engine-seed2024','Engine, seed 2024 (frozen engine)')]


def run_table(policy):
    rows=[];acc={}
    for run,label in RUNS:
        accuracy={}
        for dataset in policy['problems']:
            data=list(csv.DictReader(io.StringIO(raw(f'evaluations/{run}/{dataset}/detailed_results.csv').decode())))
            accuracy[dataset]=sum(r['is_correct'].lower()=='true' for r in data)/len(data)
        acc[run]=accuracy
        rows.append([label,fmt(100*accuracy['math500'],1),fmt(100*accuracy['gpqa'],1)])
    text=table('accuracy_runs',['Run','MATH500 acc. (%)','GPQA acc. (%)'],rows)
    engine=[r for r,_ in RUNS[1:]]
    spread=max(max(acc[r][d] for r in engine)-min(acc[r][d] for r in engine) for d in policy['problems'])
    return dict(runs_table=text,engine_spread=fmt(100*spread,1),cap=str(policy['max_new_tokens']))


def exploratory(policy):
    """Paired exploratory comparisons; every row uses the same per-problem analysis."""
    q=st.NormalDist().inv_cdf((1+policy['confidence'])/2);repeats=policy['repeats']
    scores={run:problem_scores(run,policy) for run,_ in RUNS}
    ref=sample_groups('reference-exploratory',policy)
    comparisons=[('Engine (seeds 42, 1234) minus reference',f'{2*repeats} vs {repeats}',
                  paired(scores['reference-exploratory'],[scores['engine-seed42'],scores['engine-seed1234']])),
                 ('Engine (seed 2024) minus reference',f'{repeats} vs {repeats}',
                  paired(scores['reference-exploratory'],[scores['engine-seed2024']])),
                 ('Reference repeat 0 minus repeat 1','1 vs 1',
                  paired({k:float(g[1]) for k,g in ref.items()},[{k:float(g[0]) for k,g in ref.items()}]))]
    interval=lambda delta,se:(fmt(100*(delta-q*se),1),fmt(100*(delta+q*se),1))
    rows=[[label,samples,fmt(100*delta,1),'[%s, %s]'%interval(delta,se)] for label,samples,(n,delta,se,_) in comparisons]
    (n,delta,se,z),(_,frozen,_,_),(_,half,half_se,_)=[c[2] for c in comparisons]
    low,high=interval(delta,se);split_low,split_high=interval(half,half_se)
    return dict(exploratory_table=table('exploratory',['Comparison','Samples per problem','Difference (pp)','90% CI (pp)'],rows),
                delta=fmt(100*delta,1),ci_low=low,ci_high=high,z=fmt(z,1),problems=str(n),confidence=fmt(100*policy['confidence'],0),
                margin=str(policy['equivalence_margin_pp']),split_delta=fmt(100*half,1),split_low=split_low,split_high=split_high,
                frozen_delta=fmt(100*frozen,1))


def exact_section():
    """Level 0: every recorded engine-vs-reference difference must be exactly zero."""
    d=read('exact.json');assert d['tolerance']=={'atol':0,'rtol':0}
    def mismatches(items):return sum(i[k] for i in items for k in ('decision_mismatches','visited_mismatches','pass_count_mismatches','top1_mismatches'))
    def add(label,items):
        worst=max(i['logit_max_abs'] for i in items)
        if mismatches(items) or worst or any(i['logit_squared_sum'] for i in items):
            raise ValueError('Level 0 data is not exact: '+label)
        total=lambda key:sum(i[key] for i in items)
        return [label,total('records'),total('positions'),f"{total('coordinates'):,}",mismatches(items),fmt(worst,1)]
    tiny=d['tiny'];names=('mlp3','mlp1','label3');t=[tiny[c] for c in names];c=d['constructor']
    probes=d['probes'];lengths={p['length'] for p in probes.values()};assert len(lengths)==1;length=lengths.pop()
    rows=[add('Tiny mlp3, mlp1, label3 (caps '+', '.join(str(tiny[n]['depth_cap']) for n in names)+')',t),
          add(f"Tiny label3, one {d['long']['length']}-token sequence",[d['long']]),
          add(f"Released TaH-plus 1.7B, {length} tokens",[probes['real']]),
          add(f"Full-size synthetic mlp3, mlp1, label3, {length} tokens each",[probes[n] for n in names])]
    text=table('exact',['Model','Records','Positions','Logit coordinates','Mismatches','Max logit difference'],
               [[str(x) for x in r] for r in rows])
    assert len(d['tiny_layers'])==1
    return dict(exact_table=text,tiny_layers=str(d['tiny_layers'][0]),ctor_cases=str(c['cases']),ctor_caps=f"{min(c['caps'])}–{max(c['caps'])}",
                ctor_layers=f"{min(c['layers'])}–{max(c['layers'])}")


